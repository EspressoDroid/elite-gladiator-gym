let currentLanguage = "mk";
const header = document.querySelector("[data-header]");
const menuToggle = document.querySelector("[data-menu-toggle]");
const nav = document.querySelector("[data-nav]");
const progressBar = document.querySelector(".progress span");

function translateAttribute(selector, attribute, keyAttribute) {
  document.querySelectorAll(selector).forEach((element) => {
    const key = element.getAttribute(keyAttribute);
    if (copy[currentLanguage][key]) {
      element.setAttribute(attribute, copy[currentLanguage][key]);
    }
  });
}

function updateMenuLabel() {
  const isOpen = menuToggle?.getAttribute("aria-expanded") === "true";
  if (menuToggle) {
    menuToggle.setAttribute("aria-label", copy[currentLanguage][isOpen ? "closeMenu" : "openMenu"]);
  }
}

function setLanguage(language) {
  if (!copy[language]) return;
  currentLanguage = language;
  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");
    if (copy[language][key]) {
      element.textContent = copy[language][key];
    }
  });

  translateAttribute("[data-i18n-aria]", "aria-label", "data-i18n-aria");
  translateAttribute("[data-i18n-alt]", "alt", "data-i18n-alt");

  document.querySelectorAll("[data-set-lang]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.setLang === language));
  });

  document.title = copy[language].pageTitle;
  document.querySelector('meta[name="description"]')?.setAttribute("content", copy[language].metaDescription);
  document.querySelector('meta[property="og:title"]')?.setAttribute("content", copy[language].pageTitle);
  document.querySelector('meta[property="og:description"]')?.setAttribute("content", copy[language].ogDescription);
  document.querySelector('meta[property="og:locale"]')?.setAttribute("content", language === "mk" ? "mk_MK" : "en_US");
  updateMenuLabel();
}

function closeMenu({ returnFocus = false } = {}) {
  if (!menuToggle || !nav) return;
  menuToggle.setAttribute("aria-expanded", "false");
  nav.classList.remove("is-open");
  header?.classList.remove("is-open");
  document.body.classList.remove("nav-open");
  updateMenuLabel();
  if (returnFocus) menuToggle.focus();
}

function toggleMenu() {
  if (!menuToggle || !nav) return;
  const willOpen = menuToggle.getAttribute("aria-expanded") !== "true";
  menuToggle.setAttribute("aria-expanded", String(willOpen));
  nav.classList.toggle("is-open", willOpen);
  header?.classList.toggle("is-open", willOpen);
  document.body.classList.toggle("nav-open", willOpen);
  updateMenuLabel();
  if (willOpen) nav.querySelector("a")?.focus();
}

menuToggle?.addEventListener("click", toggleMenu);
nav?.querySelectorAll("a").forEach((link) => link.addEventListener("click", () => closeMenu()));

document.addEventListener("keydown", (event) => {
  const menuIsOpen = menuToggle?.getAttribute("aria-expanded") === "true";

  if (event.key === "Escape" && menuIsOpen) {
    closeMenu({ returnFocus: true });
  }

  if (event.key === "Tab" && menuIsOpen && menuToggle && nav) {
    const menuLinks = [...nav.querySelectorAll("a")];
    const first = menuToggle;
    const last = menuLinks.at(-1);
    if (event.shiftKey && document.activeElement === first) {
      event.preventDefault();
      last?.focus();
    } else if (!event.shiftKey && document.activeElement === last) {
      event.preventDefault();
      first.focus();
    }
  }
});

document.querySelectorAll("[data-set-lang]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.setLang));
});

const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");
const revealItems = [...document.querySelectorAll("[data-reveal]")];

if (reducedMotion.matches || !("IntersectionObserver" in window)) {
  revealItems.forEach((item) => item.classList.add("is-visible"));
} else {
  const revealObserver = new IntersectionObserver(
    (entries, observer) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      });
    },
    { threshold: 0.12, rootMargin: "0px 0px -6%" }
  );
  revealItems.forEach((item) => revealObserver.observe(item));
}

const sections = [...document.querySelectorAll("main section[id]")];
const navLinks = [...document.querySelectorAll('.site-nav a[href^="#"]')];

if ("IntersectionObserver" in window) {
  const sectionObserver = new IntersectionObserver(
    (entries) => {
      const visible = entries
        .filter((entry) => entry.isIntersecting)
        .sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];
      if (!visible) return;
      navLinks.forEach((link) => {
        const active = link.getAttribute("href") === `#${visible.target.id}`;
        if (active) link.setAttribute("aria-current", "true");
        else link.removeAttribute("aria-current");
      });
    },
    { rootMargin: "-36% 0px -55%", threshold: [0, 0.1, 0.5] }
  );
  sections.forEach((section) => sectionObserver.observe(section));
}

let scrollFrame = 0;
function updateScrollState() {
  scrollFrame = 0;
  const distance = document.documentElement.scrollHeight - window.innerHeight;
  const progress = distance > 0 ? Math.min(1, Math.max(0, window.scrollY / distance)) : 0;
  if (progressBar) progressBar.style.transform = `scaleX(${progress})`;
  header?.classList.toggle("is-scrolled", window.scrollY > 18);
}

window.addEventListener(
  "scroll",
  () => {
    if (scrollFrame) return;
    scrollFrame = window.requestAnimationFrame(updateScrollState);
  },
  { passive: true }
);

window.addEventListener("resize", () => {
  if (window.innerWidth > 960) closeMenu();
  updateScrollState();
});

setLanguage("mk");
updateScrollState();
document.documentElement.classList.add("js-ready");
